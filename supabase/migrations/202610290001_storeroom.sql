-- Publish only an opaque update signal. PostgreSQL/Supabase cannot apply row
-- RLS to deleted inventory rows; publishing those DELETEs could expose tag IDs.
-- The signal is never deleted by this application and contains no stock data.
create table public.change_signal (
    singleton boolean primary key default true check (singleton),
    version bigint not null default 0,
    changed_at timestamptz not null default now()
);
insert into public.change_signal(singleton) values(true);
alter table public.change_signal enable row level security;
revoke all on public.change_signal from public, anon, authenticated;
grant select on public.change_signal to authenticated;
grant all on public.change_signal to service_role;
create policy members_read on public.change_signal for select to authenticated using ((select public.is_member()));
create function storeroom_private.signal_change() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    update public.change_signal set version=version+1,changed_at=now() where singleton;
    return null;
end $$;
revoke all on function storeroom_private.signal_change() from public, anon, authenticated;
do $$
declare tab text;
begin
    foreach tab in array array['products','readings','scans','ignored','settings','device_state'] loop
        execute format('create trigger dashboard_changed after insert or update or delete on public.%I for each statement execute function storeroom_private.signal_change()',tab);
    end loop;
    if exists(select 1 from pg_publication where pubname='supabase_realtime') then
        if exists(select 1 from pg_publication where pubname='supabase_realtime' and puballtables) then
            raise exception 'Use an explicit-table supabase_realtime publication, not FOR ALL TABLES, before applying this migration';
        end if;
        -- Remove only this application's data tables if they were selected in
        -- the dashboard already. Other projects' publication entries are kept.
        foreach tab in array array['products','readings','scans','ignored','settings','device_state','alerts'] loop
            if exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename=tab) then
                execute format('alter publication supabase_realtime drop table public.%I',tab);
            end if;
        end loop;
        if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='change_signal') then
            alter publication supabase_realtime add table public.change_signal;
        end if;
    end if;
end $$;
