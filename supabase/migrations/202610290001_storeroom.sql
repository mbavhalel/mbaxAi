-- One private storeroom. Only explicitly enrolled users can access its data.
-- Run through `supabase db push` or the project's SQL editor.
create table public.members (
    user_id uuid primary key references auth.users(id) on delete cascade
);

create function public.is_member() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.members where user_id = auth.uid()); $$;
revoke all on function public.is_member() from public, anon;
grant execute on function public.is_member() to authenticated, service_role;

create table public.products (
    uid text primary key check (uid ~ '^([0-9A-F]{2}:){3}([0-9A-F]{2})$' or uid ~ '^([0-9A-F]{2}:){6}([0-9A-F]{2})$' or uid ~ '^([0-9A-F]{2}:){9}([0-9A-F]{2})$'),
    name text not null check (length(btrim(name)) between 1 and 80),
    stock integer not null check (stock between 0 and 1000000),
    low integer not null check (low between 0 and 1000000),
    alert_level integer not null default 0 check (alert_level between 0 and 2)
);
create table public.readings (
    ts bigint primary key,
    temp double precision not null check (temp > '-Infinity'::float8 and temp < 'Infinity'::float8),
    hum double precision not null check (hum between 0 and 100)
);
create table public.scans (
    id bigint generated by default as identity primary key,
    ts bigint not null,
    kind text not null check (kind in ('scan', 'manual')),
    uid text not null,
    name text not null,
    stock_after integer check (stock_after between 0 and 1000000)
);
create index scans_uid_idx on public.scans(uid);
create table public.ignored (uid text primary key);
create table public.settings (
    singleton boolean primary key default true check (singleton),
    t_min double precision not null default 15,
    t_max double precision not null default 25,
    h_min double precision not null default 30,
    h_max double precision not null default 60,
    check (t_min > '-Infinity'::float8 and t_max < 'Infinity'::float8 and t_min < t_max),
    check (h_min >= 0 and h_max <= 100 and h_min < h_max)
);
insert into public.settings(singleton) values(true);
create table public.device_state (
    singleton boolean primary key default true check (singleton),
    status text not null default 'unknown' check (status in ('unknown','online','offline')),
    last_seen bigint
);
insert into public.device_state(singleton) values(true);
create table public.device_events (
    event_id uuid primary key,
    kind text not null,
    created_at timestamptz not null default now()
);
create table public.alerts (
    id bigint generated always as identity primary key,
    uid text not null,
    level integer not null check (level in (1,2)),
    message text not null,
    created_at timestamptz not null default now(),
    delivered_at timestamptz,
    cancelled_at timestamptz,
    claim_token uuid,
    claimed_until timestamptz,
    attempts integer not null default 0
);
create index alerts_pending_idx on public.alerts(created_at) where delivered_at is null and cancelled_at is null;

-- Browser roles have SELECT only. All mutations go through checked transactions.
alter table public.members enable row level security;
create policy members_read_self on public.members for select to authenticated using (user_id = (select auth.uid()));
revoke all on public.members from public, anon, authenticated;
grant select on public.members to authenticated;
grant all on public.members to service_role;
do $$
declare tab text;
begin
    foreach tab in array array['products','readings','scans','ignored','settings','device_state','alerts'] loop
        execute format('alter table public.%I enable row level security', tab);
        execute format('create policy members_read on public.%I for select to authenticated using ((select public.is_member()))', tab);
        execute format('revoke all on public.%I from public, anon, authenticated', tab);
        execute format('grant select on public.%I to authenticated', tab);
        execute format('grant all on public.%I to service_role', tab);
    end loop;
end $$;
alter table public.device_events enable row level security;
revoke all on public.device_events from public, anon, authenticated;
grant all on public.device_events to service_role;
grant usage, select on sequence public.scans_id_seq, public.alerts_id_seq to service_role;

-- Private helpers have no executable entry point for browser roles.
create schema if not exists storeroom_private;
revoke all on schema storeroom_private from public, anon, authenticated;
create function storeroom_private.require_member() returns void
language plpgsql security definer set search_path = '' as $$
begin
    if not public.is_member() then raise exception 'Storeroom membership required' using errcode = '42501'; end if;
end $$;
create function storeroom_private.normal_uid(raw text) returns text
language plpgsql immutable set search_path = '' as $$
declare compact text; result text := ''; i integer;
begin
    if raw is null or raw !~ '^[0-9A-Fa-f[:space:]:_-]+$' then raise exception 'Invalid tag ID' using errcode = '22023'; end if;
    compact := upper(regexp_replace(raw, '[[:space:]:_-]', '', 'g'));
    if length(compact) not in (8,14,20) then raise exception 'Invalid tag ID' using errcode = '22023'; end if;
    for i in 1..length(compact) by 2 loop
        result := result || case when i > 1 then ':' else '' end || substr(compact,i,2);
    end loop;
    return result;
end $$;
create function storeroom_private.stock_number(raw jsonb, fallback integer) returns integer
language plpgsql immutable set search_path = '' as $$
declare n numeric;
begin
    if raw is null then return fallback; end if;
    if jsonb_typeof(raw) not in ('number','string') or raw #>> '{}' !~ '^[0-9]+$' then raise exception 'Stock and alert levels must be whole numbers between 0 and 1000000' using errcode = '22023'; end if;
    n := (raw #>> '{}')::numeric;
    if n > 1000000 then raise exception 'Stock and alert levels must be between 0 and 1000000' using errcode = '22023'; end if;
    return n::integer;
end $$;
create function storeroom_private.queue_stock_alert() returns trigger
language plpgsql security definer set search_path = '' as $$
declare previous integer := 0; current_level integer;
begin
    if tg_op = 'UPDATE' then previous := old.alert_level; end if;
    current_level := case when new.stock = 0 then 2 when new.stock <= new.low then 1 else 0 end;
    new.alert_level := current_level;
    if current_level <> previous then
        -- A restock or a newer severity supersedes an unsent old warning.
        update public.alerts set cancelled_at = now() where uid = new.uid and delivered_at is null and cancelled_at is null;
        if current_level > previous then
            insert into public.alerts(uid,level,message) values(new.uid,current_level,
                case when current_level = 2 then format('ALERT: %s is out of stock',new.name)
                else format('ALERT: %s is running low, only %s left',new.name,new.stock) end);
        end if;
    end if;
    return new;
end $$;
create trigger product_alert before insert or update on public.products for each row execute function storeroom_private.queue_stock_alert();
revoke all on all functions in schema storeroom_private from public, anon, authenticated;

create function public.get_state() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare latest public.readings%rowtype; dev public.device_state%rowtype; cfg public.settings%rowtype; now_s bigint := floor(extract(epoch from now()));
begin
    perform storeroom_private.require_member();
    select * into latest from public.readings order by ts desc limit 1;
    select * into dev from public.device_state where singleton;
    select * into cfg from public.settings where singleton;
    return jsonb_build_object(
      'climate', jsonb_build_object('t',latest.temp,'h',latest.hum,'age',case when latest.ts is null then null else greatest(0,now_s-latest.ts) end),
      'device',case when dev.status='online' and (dev.last_seen is null or now_s-dev.last_seen > 90) then 'offline' else dev.status end,
      'products',coalesce((select jsonb_agg(jsonb_build_object('uid',p.uid,'name',p.name,'stock',p.stock,'low',p.low) order by lower(p.name),p.uid) from public.products p),'[]'::jsonb),
      'pending',coalesce((select jsonb_agg(x.uid order by x.latest desc) from (
          select s.uid,max(s.id) latest from public.scans s where s.kind='scan' and s.stock_after is null
          and not exists(select 1 from public.products p where p.uid=s.uid)
          and not exists(select 1 from public.ignored i where i.uid=s.uid) group by s.uid) x),'[]'::jsonb),
      'scans',coalesce((select jsonb_agg(jsonb_build_object('ts',s.ts,'kind',s.kind,'uid',s.uid,'name',s.name,'after',s.stock_after) order by s.id desc) from (select * from public.scans order by id desc limit 15) s),'[]'::jsonb),
      'settings',jsonb_build_object('tMin',cfg.t_min,'tMax',cfg.t_max,'hMin',cfg.h_min,'hMax',cfg.h_max));
end $$;

create function public.get_history(p_hours integer default 24) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare hours integer := greatest(1,least(coalesce(p_hours,24),8760)); bucket bigint;
begin
    perform storeroom_private.require_member();
    bucket := greatest(5,(hours::bigint*3600)/300);
    return coalesce((select jsonb_agg(jsonb_build_object('ts',x.ts,'t',x.t,'h',x.h) order by x.ts) from (
      select (r.ts/bucket)*bucket ts,round(avg(r.temp)::numeric,1) t,round(avg(r.hum)::numeric,1) h
      from public.readings r where r.ts >= extract(epoch from now())-hours::bigint*3600
      group by 1) x),'[]'::jsonb);
end $$;

create function public.manage_stock(p_action text, p_data jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare tag text; item public.products%rowtype; label text; stock_n integer; low_n integer; tmin float8; tmax float8; hmin float8; hmax float8;
begin
    perform storeroom_private.require_member();
    if p_data is null or jsonb_typeof(p_data) <> 'object' then raise exception 'Use a JSON object' using errcode = '22023'; end if;
    perform pg_advisory_xact_lock(774411);
    if p_action in ('add','update','delete','ignore') then tag := storeroom_private.normal_uid(p_data->>'uid'); end if;
    if p_action = 'add' then
        label := btrim(p_data->>'name');
        if label is null or length(label) not between 1 and 80 then raise exception 'Enter an item name (1 to 80 characters)' using errcode = '22023'; end if;
        insert into public.products(uid,name,stock,low) values(tag,label,storeroom_private.stock_number(p_data->'stock',0),storeroom_private.stock_number(p_data->'low',3));
        delete from public.ignored where uid=tag;
    elsif p_action = 'update' then
        select * into item from public.products where uid=tag for update;
        if not found then raise exception 'Item not found' using errcode = 'P0002'; end if;
        label := coalesce(p_data->>'name',item.name);
        label := btrim(label);
        if length(label) not between 1 and 80 then raise exception 'Enter an item name (1 to 80 characters)' using errcode = '22023'; end if;
        stock_n := storeroom_private.stock_number(p_data->'stock',item.stock);
        low_n := storeroom_private.stock_number(p_data->'low',item.low);
        update public.products set name=label,stock=stock_n,low=low_n where uid=tag;
        if stock_n <> item.stock then
            insert into public.scans(ts,kind,uid,name,stock_after) values(floor(extract(epoch from now())),'manual',tag,label,stock_n);
        end if;
    elsif p_action = 'delete' then
        update public.alerts set cancelled_at=now() where uid=tag and delivered_at is null and cancelled_at is null;
        delete from public.products where uid=tag;
    elsif p_action = 'ignore' then
        insert into public.ignored(uid) values(tag) on conflict do nothing;
    elsif p_action = 'clear' then
        update public.alerts set cancelled_at=now() where delivered_at is null and cancelled_at is null;
        delete from public.products;
        delete from public.scans;
        delete from public.ignored;
    elsif p_action = 'settings' then
        begin
            tmin := (p_data->>'tMin')::float8; tmax := (p_data->>'tMax')::float8;
            hmin := (p_data->>'hMin')::float8; hmax := (p_data->>'hMax')::float8;
        exception when invalid_text_representation or numeric_value_out_of_range then
            raise exception 'Enter a finite number for every range' using errcode='22023';
        end;
        if tmin is null or tmax is null or hmin is null or hmax is null
          or not (tmin > '-Infinity'::float8 and tmax < 'Infinity'::float8 and tmin < tmax)
          or not (hmin >= 0 and hmax <= 100 and hmin < hmax) then
            raise exception 'Enter valid ranges; minimum must be below maximum and humidity within 0 to 100' using errcode='22023';
        end if;
        update public.settings set t_min=tmin,t_max=tmax,h_min=hmin,h_max=hmax where singleton;
    else
        raise exception 'Unknown action' using errcode = '22023';
    end if;
    return jsonb_build_object('ok',true);
end $$;

-- The service role is available only inside trusted Edge Functions, never in HTML.
create function public.ingest_device(p_event jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare kind text; tag text; item public.products%rowtype; remaining integer; event_uuid uuid; now_s bigint := floor(extract(epoch from now())); t float8; h float8; status_s text;
begin
    if p_event is null or jsonb_typeof(p_event) <> 'object' then raise exception 'Use a JSON object' using errcode = '22023'; end if;
    kind := p_event->>'type';
    if kind not in ('climate','scan','status') or kind is null then raise exception 'Invalid device event type' using errcode = '22023'; end if;
    if kind='scan' then
        tag := storeroom_private.normal_uid(p_event->>'uid');
        if p_event->>'event_id' is null then raise exception 'A scan needs a stable UUID event_id for retries' using errcode='22023'; end if;
    elsif kind='climate' then
        begin t := (p_event->>'t')::float8; h := (p_event->>'h')::float8;
        exception when invalid_text_representation or numeric_value_out_of_range then raise exception 'Invalid climate reading' using errcode='22023'; end;
        if t is null or h is null or not (t > '-Infinity'::float8 and t < 'Infinity'::float8 and h between 0 and 100) then raise exception 'Invalid climate reading' using errcode='22023'; end if;
    else
        status_s := p_event->>'status';
        if status_s is null or status_s not in ('online','offline') then raise exception 'Invalid device status' using errcode='22023'; end if;
    end if;
    if p_event ? 'event_id' then
        begin event_uuid := (p_event->>'event_id')::uuid;
        exception when invalid_text_representation then raise exception 'Invalid event_id UUID' using errcode='22023'; end;
        if event_uuid is null then raise exception 'Invalid event_id UUID' using errcode='22023'; end if;
    end if;
    perform pg_advisory_xact_lock(774411);
    if event_uuid is not null then
        insert into public.device_events(event_id,kind) values(event_uuid,kind) on conflict do nothing;
        if not found then return jsonb_build_object('ok',true,'duplicate',true); end if;
    end if;
    if kind='climate' then
        insert into public.readings(ts,temp,hum) values(now_s,t,h) on conflict(ts) do update set temp=excluded.temp,hum=excluded.hum;
        delete from public.readings where ts < now_s - 365::bigint*86400;
    elsif kind='scan' then
        select * into item from public.products where uid=tag for update;
        if found then
            remaining := greatest(0,item.stock-1);
            update public.products set stock=remaining where uid=tag;
            insert into public.scans(ts,kind,uid,name,stock_after) values(now_s,'scan',tag,item.name,remaining);
        else
            insert into public.scans(ts,kind,uid,name,stock_after) values(now_s,'scan',tag,'Unregistered tag',null);
            delete from public.ignored where uid=tag;
        end if;
    end if;
    update public.device_state set status=case when kind='status' then status_s else 'online' end,last_seen=now_s where singleton;
    return jsonb_build_object('ok',true,'duplicate',false);
end $$;

-- Leasing makes concurrent Edge Function invocations safe. A worker can recover
-- an expired lease; Telegram itself has no idempotency key, so delivery is at-least-once.
create function public.claim_alerts(p_claim uuid) returns setof public.alerts
language sql security definer set search_path = '' as $$
    update public.alerts a set claim_token=p_claim,claimed_until=now()+interval '90 seconds',attempts=attempts+1
    where a.id in (select id from public.alerts where delivered_at is null and cancelled_at is null
      and (claimed_until is null or claimed_until < now()) order by id for update skip locked limit 5)
    returning a.*;
$$;
create function public.finish_alert(p_id bigint,p_claim uuid,p_success boolean) returns void
language sql security definer set search_path = '' as $$
    update public.alerts set delivered_at=case when p_success then now() else delivered_at end,
      claim_token=null,claimed_until=case when p_success then null else now()+interval '30 seconds' end
    where id=p_id and claim_token=p_claim and delivered_at is null;
$$;

