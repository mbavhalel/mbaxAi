grant execute on function public.get_state(), public.get_history(integer), public.manage_stock(text,jsonb) to authenticated;
revoke all on function public.ingest_device(jsonb), public.claim_alerts(uuid), public.finish_alert(bigint,uuid,boolean) from public, anon, authenticated;
